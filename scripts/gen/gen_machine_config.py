#!/usr/bin/env python3
"""Bakes the selected machine TOML into a constexpr C++ header.

Usage: scripts/gen/gen_machine_config.py [--check]
  --check  fail when the checked-in ... nothing is checked in; the output
           always lands in the build tree (JIT_TEMPLATES_OUT-style env or
           MACHINE_CONFIG_OUT).

Why generated: the machine layout is data (port windows, memory windows,
RAM size). Keeping it in TOML means changing the machine is an edit plus a
rebuild; keeping it in C++ means every tweak is a diff across source files
that also contain logic. The generator validates device names against the
MachineDevice spelling so a typo dies at build time, not at boot.

The emitted header is constexpr-only: it adds no link-time dependencies,
so any TU (core, wasm, tools) can include it.
"""
import argparse
import os
import pathlib
import sys

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover
    sys.exit("gen_machine_config.py needs python3.11+ (tomllib)")

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "machines"
DEFAULT_MACHINE = os.environ.get("MICRO_FORGE_MACHINE", "cinux")
DEFAULT_OUT = (pathlib.Path(__file__).resolve().parents[2] /
               "include/micro_forge/generated/machine_config_generated.hpp")
OUTPUT = pathlib.Path(os.environ.get("MACHINE_CONFIG_OUT", DEFAULT_OUT))

# Device spellings accepted in the TOML, one per MachineDevice enumerator.
DEVICES = {
    "serial": "kSerial",
    "pit": "kPit",
    "board": "kBoard",
    "rtc": "kRtc",
    "post": "kPost",
    "fw_cfg": "kFwCfg",
    "pci": "kPci",
    "kbd_data": "kKbdData",
    "kbd_status": "kKbdStatus",
    "pic_master": "kPicMaster",
    "pic_slave": "kPicSlave",
    "ahci": "kAhci",
    "lapic": "kLapic",
    "io_apic": "kIoApic",
}


def emit(dev: dict) -> str:
    out = [
        "/* Generated by scripts/gen/gen_machine_config.py from"
        f" machines/{dev['name']}.toml — do not edit. */",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        '#include "micro_forge/base/machine_config.hpp"',
        "",
        "namespace micro_forge::generated {",
        "",
        "/// The described machine's default guest RAM in bytes.",
        f"inline constexpr std::uint64_t kDefaultRamSize = {dev['ram_size']}ULL;",
        "/// Line framebuffer reservation riding the RAM tail.",
        f"inline constexpr std::uint64_t kLfbSize = {dev['lfb_size']}ULL;",
        "/// MMIO debug-exit register base.",
        f"inline constexpr std::uint64_t kDebugExitBase = {dev['debug_exit_base']}ULL;",  # already hex
        "",
        "/// Port-space windows, verbatim from the description.",
        f"inline constexpr std::array<PortWindow, {len(dev['ports'])}> kPortWindows{{{{",
    ]
    for p in dev["ports"]:
        out.append(f"    {{{hex(p['base'])}ULL, {p['size']}, "
                   f"MachineDevice::{DEVICES[p['device']]}}},")
    out.append("}};")
    out.append("")
    out.append("/// Memory-mapped windows, verbatim from the description.")
    out.append(f"inline constexpr std::array<MemoryWindow, {len(dev['windows'])}> kMemoryWindows{{{{")
    for w in dev["windows"]:
        d = DEVICES[w["device"]]
        out.append(f"    {{{hex(w['base'])}ULL, {w['size']}, MachineDevice::{d}}},")
    out.append("}};")
    out.append("")
    a = dev["ahci"]
    out += [
        "/// AHCI PCI identity behind mechanism-1 config space.",
        f"inline constexpr std::uint16_t kAhciVendor = {hex(a['vendor'])};",
        f"inline constexpr std::uint16_t kAhciDevice = {hex(a['device'])};",
        f"inline constexpr std::uint32_t kAhciClass = {hex(a['class'])}U;",
        f"inline constexpr std::uint8_t kAhciIrq = {a['irq']};",
        "",
        "/// Host-side default images for the example tools.",
        'inline constexpr const char* kLoaderKernelPath = "'
        + dev["loader"]["kernel"] + '";',
        'inline constexpr const char* kLoaderDiskPath = "'
        + dev["loader"]["disk"] + '";',
        "",
        "/// The wasm artifact's linear-memory sizing (guest RAM in MiB).",
        f"inline constexpr std::uint64_t kWasmGuestRamMb = {dev['wasm_ram_mb']}ULL;",
        "",
        "/// Whether this machine boots with the JIT warmed on (x86-64 hosts).",
        f"inline constexpr bool kJitEnabled = {'true' if dev['jit'] else 'false'};",
        "",
        "} // namespace micro_forge::generated",
        "",
    ]
    return "\n".join(out)


def load(machine: str) -> dict:
    path = SOURCE / f"{machine}.toml"
    if not path.exists():
        sys.exit(f"unknown machine '{machine}': {path} does not exist")
    raw = tomllib.loads(path.read_text())
    dev = {
        "name": machine,
        "ram_size": int(raw["machine"]["ram_mb"]) << 20,
        "lfb_size": int(raw["machine"]["lfb_mb"]) << 20,
        "debug_exit_base": hex(raw["machine"]["debug_exit_base"]),
        "ahci": raw["ahci"],
        "ports": raw.get("ports", []),
        "windows": raw.get("windows", []),
        "loader": raw["loader"],
        "wasm_ram_mb": int(raw["wasm"]["guest_ram_mb"]),
        "jit": bool(raw["jit"]["enabled"]),
    }
    for w in dev["ports"] + dev["windows"]:
        if w["device"] not in DEVICES:
            sys.exit(f"{path}: unknown device name '{w['device']}' "
                     f"(known: {', '.join(sorted(DEVICES))})")
    return dev


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail instead of rewriting when stale")
    args = parser.parse_args()

    text = emit(load(DEFAULT_MACHINE))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            sys.exit(f"{OUTPUT} is stale; rerun the generator")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f"[gen-machine] wrote {DEFAULT_MACHINE} "
          f"({len(dev_ports(DEFAULT_MACHINE))} ports, "
          f"{len(dev_windows(DEFAULT_MACHINE))} windows) -> {OUTPUT}")


def dev_ports(machine: str) -> list:
    return load(machine)["ports"]


def dev_windows(machine: str) -> list:
    return load(machine)["windows"]


if __name__ == "__main__":
    main()
